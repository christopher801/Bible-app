export const TRANSLATIONS_UI = { en, es, ht };

export function translate(lang, key, params) {
  const dict = TRANSLATIONS_UI[lang] || en;
  let str = dict[key] !== undefined ? dict[key] : en[key] !== undefined ? en[key] : key;
  if (params) {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  }
  return str;
}
